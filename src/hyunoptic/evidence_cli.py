"""Review consistency of locally produced HyunOptic research evidence files.

No raw images, annotation files, or per-case data are processed here.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
from .evidence_gate import review_evidence, save_evidence_review


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(
        description="Read-only research evidence-package gate; NOT a claim of clinical validation"
    )
    p.add_argument("--sources", type=Path, required=True,
                   help="JSON generated by hyunoptic-verify-sources")
    p.add_argument("--papila-inventory", type=Path, required=True)
    p.add_argument("--model-lock", type=Path, required=True)
    p.add_argument("--chaksu-audit", type=Path, required=True,
                   help="audit_aggregate.json from hyunoptic-chaksu-audit")
    p.add_argument("--external-aggregate", type=Path, required=True)
    p.add_argument("--output", type=Path, default=Path("reports/evidence_review.json"))
    p.add_argument("--strict", action="store_true",
                   help="Return code 2 when required evidence package checks fail")
    args = p.parse_args(argv)
    try:
        report = review_evidence(
            sources=args.sources,
            papila_inventory=args.papila_inventory,
            model_lock=args.model_lock,
            chaksu_audit=args.chaksu_audit,
            external_aggregate=args.external_aggregate,
        )
        save_evidence_review(report, args.output)
    except (ValueError, OSError, KeyError, TypeError, json.JSONDecodeError) as exc:
        p.error(str(exc))
    print(json.dumps({
        "review_json": str(args.output),
        "n_passed": report["n_passed"],
        "n_required": report["n_total"],
        "research_package_consistent": report["all_required_artifacts_consistent"],
        "scientific_validity_established": False,
        "clinical_accuracy_established": False,
    }, indent=2))
    return 2 if args.strict and not report["all_required_artifacts_consistent"] else 0


if __name__ == "__main__":
    raise SystemExit(main())
