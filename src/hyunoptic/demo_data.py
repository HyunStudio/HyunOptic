"""Generate clearly-marked SYNTHETIC PAPILA-shaped and Chákṣu-shaped demo data.

The images are procedurally drawn fundus-like pictures, not photographs of any
person. Both outputs carry a SYNTHETIC_DEMO_DATA.txt marker, are far smaller
than the published datasets, and therefore always run as partial/unverified.
"""
from __future__ import annotations

import argparse
import io
import zipfile
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw, ImageFilter

from .measure import polygon_mask
from .ui.workspace import SYNTHETIC_MARKER

MARKER_TEXT = ("SYNTHETIC DEMO DATA generated by hyunoptic-demo-data.\n"
               "Procedurally drawn; contains no patient images. Never cite results from it.\n")


def _fundus(rng: np.random.Generator, size: tuple[int, int], disc: tuple[float, float, float, float],
            cup: tuple[float, float, float, float]) -> Image.Image:
    w, h = size
    yy, xx = np.mgrid[0:h, 0:w]
    cx, cy, r = w / 2, h / 2, min(w, h) * 0.47
    dist = np.hypot(xx - cx, yy - cy) / r
    base = np.clip(1.15 - 0.55 * dist ** 2, 0, 1)
    tint = rng.uniform(0.9, 1.1)
    rgb = np.stack([200 * base * tint, 78 * base, 38 * base], axis=-1)
    dcx, dcy, drx, dry = disc
    glow = np.exp(-(((xx - dcx) / (drx * 1.6)) ** 2 + ((yy - dcy) / (dry * 1.6)) ** 2))
    rgb += glow[..., None] * np.array([50, 70, 40])
    img = Image.fromarray(np.clip(rgb, 0, 255).astype(np.uint8))
    draw = ImageDraw.Draw(img)
    for _ in range(9):  # vessels radiating from the disc
        angle = rng.uniform(0, 2 * np.pi)
        x, y = dcx, dcy
        width = int(rng.integers(2, 5))
        for _ in range(28):
            angle += rng.normal(0, 0.18)
            nx, ny = x + np.cos(angle) * w / 45, y + np.sin(angle) * w / 45
            draw.line([(x, y), (nx, ny)], fill=(120, 20, 18), width=width)
            x, y = nx, ny
    draw.ellipse((dcx - drx, dcy - dry, dcx + drx, dcy + dry), fill=(236, 170, 110))
    ccx, ccy, crx, cry = cup
    draw.ellipse((ccx - crx, ccy - cry, ccx + crx, ccy + cry), fill=(250, 214, 160))
    img = img.filter(ImageFilter.GaussianBlur(1.6))
    vignette = (dist <= 1.0).astype(np.uint8)[..., None]
    return Image.fromarray(np.asarray(img) * vignette)


def _ellipse(cx, cy, rx, ry, n=60):
    t = np.linspace(0, 2 * np.pi, n, endpoint=False)
    return np.column_stack((cx + rx * np.cos(t), cy + ry * np.sin(t)))


def _geometry(rng, w, h):
    dcx, dcy = w * rng.uniform(0.55, 0.62), h * rng.uniform(0.45, 0.55)
    drx, dry = w * rng.uniform(0.07, 0.08), h * rng.uniform(0.11, 0.125)
    ratio = rng.uniform(0.3, 0.75)
    return (dcx, dcy, drx, dry), (dcx + drx * 0.08, dcy - dry * 0.04, drx * ratio * 0.95, dry * ratio)


def _reader(rng, disc, cup, spread):
    """One expert's annotation: the true geometry with reader-specific error."""
    dcx, dcy, drx, dry = disc
    ccx, ccy, crx, cry = cup
    d = (dcx + rng.normal(0, 1.5), dcy + rng.normal(0, 1.5), drx * rng.normal(1, .03), dry * rng.normal(1, .03))
    c = (ccx + rng.normal(0, 1.5), ccy + rng.normal(0, 1.5), crx * rng.normal(1, spread),
         cry * rng.normal(1, spread))
    c = (c[0], c[1], min(c[2], d[2] * 0.9), min(c[3], d[3] * 0.9))
    return d, c


def make_papila(root: str | Path, *, patients: int = 20, seed: int = 7, size=(640, 480)) -> Path:
    base = Path(root)
    images = base / "FundusImages"
    contours = base / "ExpertsSegmentations" / "Contours"
    images.mkdir(parents=True, exist_ok=False)
    contours.mkdir(parents=True)
    (base / SYNTHETIC_MARKER).write_text(MARKER_TEXT, encoding="utf-8")
    rng = np.random.default_rng(seed)
    for p in range(1, patients + 1):
        for eye in ("OD", "OS"):
            name = f"RET{p:03d}{eye}"
            disc, cup = _geometry(rng, *size)
            _fundus(rng, size, disc, cup).save(images / f"{name}.jpg", quality=88)
            spread = 0.18 if rng.random() < 0.3 else 0.05
            for expert in ("exp1", "exp2"):
                d, c = _reader(rng, disc, cup, spread)
                np.savetxt(contours / f"{name}_disc_{expert}.txt", _ellipse(*d), fmt="%.2f")
                np.savetxt(contours / f"{name}_cup_{expert}.txt", _ellipse(*c), fmt="%.2f")
    return base


def _png(image: Image.Image, fmt: str = "PNG") -> bytes:
    buffer = io.BytesIO()
    image.save(buffer, format=fmt)
    return buffer.getvalue()


def make_chaksu(path: str | Path, *, per_camera: int = 6, seed: int = 11) -> Path:
    path = Path(path)
    if path.exists():
        raise FileExistsError(f"{path} already exists")
    path.parent.mkdir(parents=True, exist_ok=True)
    rng = np.random.default_rng(seed)
    sizes = {"Bosch": (480, 360), "Forus": (512, 384), "Remidio": (480, 640)}
    with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as zf:
        zf.writestr(f"Test/{SYNTHETIC_MARKER}", MARKER_TEXT)
        for camera, (w, h) in sizes.items():
            for k in range(per_camera):
                stem = f"Image{k + 1:03d}"
                disc, cup = _geometry(rng, w, h)
                zf.writestr(f"Test/1.0_Original_Fundus_Images/{camera}/{stem}.png",
                            _png(_fundus(rng, (w, h), disc, cup)))
                spread = 0.2 if rng.random() < 0.35 else 0.05
                for expert in range(1, 6):
                    d, c = _reader(rng, disc, cup, spread)
                    for structure, shape in (("Disc", d), ("Cup", c)):
                        mask = polygon_mask(_ellipse(*shape, n=90), (w, h)).astype(np.uint8) * 255
                        zf.writestr(f"Test/3.0_Doctors_Annotations_Binary_OD_OC/Expert {expert}/{camera}/"
                                    f"{structure}/{stem}.tif", _png(Image.fromarray(mask), "TIFF"))
    return path


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description="Create SYNTHETIC demo datasets (no patient data) for trying the app")
    p.add_argument("--output-dir", type=Path, default=Path("demo_data"))
    p.add_argument("--patients", type=int, default=20)
    p.add_argument("--per-camera", type=int, default=6)
    a = p.parse_args(argv)
    try:
        root = make_papila(a.output_dir / "PAPILA_SYNTHETIC", patients=a.patients)
        archive = make_chaksu(a.output_dir / "Chaksu_SYNTHETIC_Test.zip", per_camera=a.per_camera)
    except (OSError, ValueError) as exc:
        p.error(str(exc))
    print(f"Synthetic PAPILA-shaped folder: {root}")
    print(f"Synthetic Chaksu-shaped Test.zip: {archive}")
    print("Set these on the Datasets page. Results from them are always partial and must never be cited.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
